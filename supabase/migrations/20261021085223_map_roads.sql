-- Road storage and validation. Loaded after the base tables in schema.sql.
create table if not exists fauxlore.map_roads (
  id bigint generated by default as identity primary key,
  type text not null check(type in ('trail','highway','imperial')),
  anchors jsonb not null check(jsonb_typeof(anchors)='array'),
  segments jsonb not null check(jsonb_typeof(segments)='array'),
  created_by bigint not null references fauxlore.accounts,
  created_at timestamptz not null default now()
);
alter table fauxlore.map_roads enable row level security;
revoke all on fauxlore.map_roads from public,anon,authenticated;
revoke all on sequence fauxlore.map_roads_id_seq from public,anon,authenticated;

create or replace function fauxlore.create_road(body jsonb, account_id bigint) returns jsonb
language plpgsql security invoker set search_path='' as $$
declare anchor jsonb; point jsonb; segment jsonb; anchors jsonb:=body->'anchors'; segments jsonb:=body->'segments';
  p fauxlore.provinces; q fauxlore.provinces; m fauxlore.map_markers; r fauxlore.map_roads;
  i integer; n integer; x numeric; y numeric; bounds jsonb;
begin
  if body-array['type','anchors','segments']<>'{}' or body->>'type' is null or body->>'type' not in ('trail','highway','imperial')
    or jsonb_typeof(anchors) is distinct from 'array' or jsonb_typeof(segments) is distinct from 'array' then
    raise sqlstate '22023' using message='Некорректная дорога'; end if;
  n:=jsonb_array_length(anchors);
  if n<2 or n>64 or jsonb_array_length(segments)<>n-1 then raise sqlstate '22023' using message='Нужно от 2 до 64 точек дороги'; end if;
  select value_json into bounds from fauxlore._settings where key='region';
  for i in 0..n-1 loop
    anchor:=anchors->i;
    if jsonb_typeof(anchor) is distinct from 'object' or anchor-array['kind','province_id','marker_id','x','y']<>'{}'
      or jsonb_typeof(anchor->'province_id') is distinct from 'number'
      or jsonb_typeof(anchor->'x') is distinct from 'number' or jsonb_typeof(anchor->'y') is distinct from 'number' then
      raise sqlstate '22023' using message='Некорректная точка привязки'; end if;
    select * into p from fauxlore.provinces where id=(anchor->>'province_id')::integer and kind='land';
    if not found then raise sqlstate '22023' using message='Дороги можно прокладывать только по суше'; end if;
    x:=(anchor->>'x')::numeric;y:=(anchor->>'y')::numeric;
    if x<(bounds->>0)::numeric or y<(bounds->>1)::numeric or x>=(bounds->>2)::numeric or y>=(bounds->>3)::numeric then
      raise sqlstate '22023' using message='Точка вне игровой области'; end if;
    if anchor->>'kind'='province' then
      if anchor?'marker_id' or abs(x-(p.center->>0)::numeric)>.001 or abs(y-(p.center->>1)::numeric)>.001 then
        raise sqlstate '22023' using message='Укажите центр провинции'; end if;
    elsif anchor->>'kind'='marker' then
      if jsonb_typeof(anchor->'marker_id') is distinct from 'number' then raise sqlstate '22023' using message='Не указан маркер'; end if;
      select * into m from fauxlore.map_markers where id=(anchor->>'marker_id')::bigint and province_id=p.id;
      if not found or abs(x-m.x)>.001 or abs(y-m.y)>.001 then raise sqlstate '22023' using message='Маркер изменён или удалён'; end if;
    else raise sqlstate '22023' using message='Неизвестный вид точки привязки'; end if;
  end loop;
  for i in 0..n-2 loop
    segment:=segments->i;
    if jsonb_typeof(segment) is distinct from 'array' then raise sqlstate '22023' using message='Некорректный участок'; end if;
    if jsonb_array_length(segment)<2 or jsonb_array_length(segment)>8192 then raise sqlstate '22023' using message='Некорректная длина участка'; end if;
    select * into p from fauxlore.provinces where id=(anchors->i->>'province_id')::integer;
    select * into q from fauxlore.provinces where id=(anchors->(i+1)->>'province_id')::integer;
    for point in select * from jsonb_array_elements(segment) loop
      if jsonb_typeof(point) is distinct from 'array' then raise sqlstate '22023' using message='Некорректная геометрия'; end if;
      if jsonb_array_length(point)<>2 or jsonb_typeof(point->0) is distinct from 'number' or jsonb_typeof(point->1) is distinct from 'number' then
        raise sqlstate '22023' using message='Некорректные координаты дороги'; end if;
      x:=(point->>0)::numeric;y:=(point->>1)::numeric;
      if x<(bounds->>0)::numeric or y<(bounds->>1)::numeric or x>=(bounds->>2)::numeric or y>=(bounds->>3)::numeric
        or not ((x>=(p.bbox->>0)::numeric and x<(p.bbox->>2)::numeric and y>=(p.bbox->>1)::numeric and y<(p.bbox->>3)::numeric)
          or (x>=(q.bbox->>0)::numeric and x<(q.bbox->>2)::numeric and y>=(q.bbox->>1)::numeric and y<(q.bbox->>3)::numeric)) then
        raise sqlstate '22023' using message='Участок вне выбранных провинций'; end if;
    end loop;
    if abs((segment->0->>0)::numeric-(anchors->i->>'x')::numeric)>.001
      or abs((segment->0->>1)::numeric-(anchors->i->>'y')::numeric)>.001
      or abs((segment->-1->>0)::numeric-(anchors->(i+1)->>'x')::numeric)>.001
      or abs((segment->-1->>1)::numeric-(anchors->(i+1)->>'y')::numeric)>.001 then
      raise sqlstate '22023' using message='Участок не совпадает с точками привязки'; end if;
  end loop;
  insert into fauxlore.map_roads(type,anchors,segments,created_by) values(body->>'type',anchors,segments,account_id) returning * into r;
  return jsonb_build_object('id',r.id,'type',r.type,'anchors',r.anchors,'segments',r.segments);
end $$;
revoke all on function fauxlore.create_road(jsonb,bigint) from public,anon,authenticated;


create or replace function fauxlore.map_payload() returns jsonb
language sql stable security invoker set search_path='' as $$
with s as (select jsonb_object_agg(key,value_json) as data from fauxlore._settings),
visible as (select p.* from fauxlore.provinces p cross join s where
  (p.bbox->>0)::numeric<(s.data->'region'->>2)::numeric and
  (p.bbox->>2)::numeric>(s.data->'region'->>0)::numeric and
  (p.bbox->>1)::numeric<(s.data->'region'->>3)::numeric and
  (p.bbox->>3)::numeric>(s.data->'region'->>1)::numeric),
layers as (select v.province_id,jsonb_object_agg(v.layer,jsonb_build_object('id',c.id,'name',c.name,'color',c.color)) as data
  from fauxlore.province_values v join visible p on p.id=v.province_id
  join fauxlore.map_categories c on c.layer=v.layer and c.id=v.category_id group by v.province_id)
select s.data||jsonb_build_object('provinces',coalesce((select jsonb_agg(case when p.kind='sea' then
  to_jsonb(p)-array['province_type','courts','population','development','taxes','production','warehouse','control','tension','has_capital_marker','has_city_marker']
  else to_jsonb(p)||jsonb_build_object('layers',coalesce(l.data,'{}'),'control_color',c.color) end order by p.id)
  from visible p left join layers l on l.province_id=p.id left join fauxlore.map_categories c on c.layer='states' and c.name=p.control),'[]'),
  'roads',coalesce((select jsonb_agg(jsonb_build_object('id',r.id,'type',r.type,'anchors',r.anchors,'segments',r.segments) order by r.id)
    from fauxlore.map_roads r where exists(select 1 from jsonb_array_elements(r.anchors) anchor join visible p on p.id=(anchor->>'province_id')::integer)),'[]'),
  'categories',coalesce((select jsonb_agg(to_jsonb(c) order by layer,id) from fauxlore.map_categories c),'[]'),
  'markers',coalesce((select jsonb_agg(to_jsonb(m)||jsonb_build_object('state_name',c.name) order by m.id)
    from fauxlore.map_markers m join visible p on p.id=m.province_id
    left join fauxlore.map_categories c on c.layer=m.state_layer and c.id=m.state_id),'[]')) from s
$$;


create or replace function fauxlore.api(path text, method text, body jsonb, request_id uuid) returns jsonb
language plpgsql security definer set search_path='' as $$
declare a fauxlore.accounts; p fauxlore.provinces; m fauxlore.map_markers; result jsonb;
  previous fauxlore.operations; fingerprint text; id_value integer; marker_id bigint; state_value integer;
  avatar text; mime_value text; changes jsonb;
begin
  if length(path)>150 or method not in ('GET','POST','PATCH','PUT','DELETE') or
    jsonb_typeof(body) is distinct from 'object' or octet_length(body::text)>2900000 then
    raise sqlstate '22023' using message='Некорректный запрос'; end if;
  if path='health' and method='GET' then return jsonb_build_object('ok',true,'database','supabase'); end if;
  if path='map' and method='GET' then
    if not exists(select 1 from fauxlore._settings where key='migration_ready' and value_json='true') then
      raise sqlstate '55000' using message='Перенос данных ещё не завершён'; end if;
    return fauxlore.map_payload();
  end if;
  if path='auth/me' and method='GET' and auth.uid() is null then return '{"user":null}'; end if;
  a:=fauxlore.current_account();
  if path like 'admin/%' and a.role<>'admin' then raise sqlstate '42501' using message='Нужна роль администратора'; end if;
  if path='auth/me' and method='GET' then return jsonb_build_object('user',fauxlore.profile(a)); end if;
  if path='profile' and method='GET' then return fauxlore.profile(a); end if;
  if path='preferences' and method='GET' then return coalesce((select settings from fauxlore.user_preferences where account_id=a.id),'{}'); end if;
  if method='GET' then raise sqlstate 'P0002' using message='Метод API не найден'; end if;
  if request_id is null then raise sqlstate '22023' using message='Нужен идентификатор команды'; end if;
  fingerprint:=md5(jsonb_build_array(method,path,body)::text);
  perform pg_advisory_xact_lock(hashtextextended(a.id::text||':'||request_id::text,0));
  select * into previous from fauxlore.operations o where account_id=a.id and o.request_id=api.request_id;
  if found then
    if previous.fingerprint<>fingerprint then raise sqlstate '22023' using message='Идентификатор команды уже использован'; end if;
    return previous.result;
  end if;
  if path='preferences' and method='PUT' then
    select coalesce(jsonb_object_agg(key,value),'{}') into changes from jsonb_each(body) where key=any(array['layer','markers','information','showIds']);
    if octet_length(changes::text)>8192 then raise sqlstate '22023' using message='Слишком большой набор настроек'; end if;
    insert into fauxlore.user_preferences values(a.id,changes) on conflict(account_id) do update set settings=excluded.settings;
    result:='{"ok":true}';
  elsif path='profile/avatar' and method='POST' then
    avatar:=body->>'image_data';
    if avatar is not null then
      if avatar!~'^data:image/(png|jpeg|gif|webp);base64,[A-Za-z0-9+/=\r\n]+$' then raise sqlstate '22023' using message='Неподдерживаемое изображение'; end if;
      mime_value:=split_part(substr(avatar,6),';',1);avatar:=split_part(avatar,',',2);
      if octet_length(decode(avatar,'base64'))>2097152 then raise sqlstate '22023' using message='Аватар должен быть не больше 2 МБ'; end if;
    end if;
    update fauxlore.accounts set avatar_base64=avatar,avatar_type=mime_value where id=a.id;
    result:='{"ok":true}';
  elsif path~'^admin/categories/(states|races|religions|resources|trade|climate)/[0-9]+$' and method='PATCH' then
    if body-'color'<>'{}' or jsonb_typeof(body->'color') is distinct from 'string' or
      (body->>'color')!~'^#[0-9a-fA-F]{6}$' then
      raise sqlstate '22023' using message='Укажите цвет в формате #RRGGBB'; end if;
    update fauxlore.map_categories set color=lower(body->>'color')
      where layer=split_part(path,'/',3) and id=split_part(path,'/',4)::integer
      returning to_jsonb(map_categories.*) into result;
    if not found then raise sqlstate 'P0002' using message='Значение параметра не найдено'; end if;
  elsif path='admin/roads' and method='POST' then
    result:=fauxlore.create_road(body,a.id);
  elsif path~'^admin/roads/[0-9]+$' and method='DELETE' then
    marker_id:=split_part(path,'/',3)::bigint;delete from fauxlore.map_roads where id=marker_id;
    if not found then raise sqlstate 'P0002' using message='Дорога не найдена'; end if;
    result:=jsonb_build_object('id',marker_id,'deleted',true);
  elsif path in ('admin/provinces/bulk-preview','admin/provinces/bulk-edit') and method='POST' then
    result:=fauxlore.bulk_edit(body,path='admin/provinces/bulk-edit');
  elsif path~'^admin/provinces/\d+$' and method='PATCH' then
    result:=fauxlore.edit_province(split_part(path,'/',3)::integer,body);
  elsif path~'^provinces/\d+/name$' and method='PATCH' then
    id_value:=split_part(path,'/',2)::integer;
    if not exists(select 1 from fauxlore.province_values v join fauxlore.account_states s
      on s.state_id=v.category_id and s.account_id=a.id where v.province_id=id_value and v.layer='states') then
      raise sqlstate '42501' using message='Вы не владеете государством этой провинции'; end if;
    if body-'name'<>'{}' then raise sqlstate '22023' using message='Разрешено менять только название'; end if;
    result:=fauxlore.edit_province(id_value,body);result:=jsonb_build_object('id',id_value,'name',result->'name');
  elsif path='admin/markers' and method='POST' then
    if body-array['province_id','x','y','type','name','state_id']<>'{}' or body->>'type' not in ('capital','city','fortress','port') then
      raise sqlstate '22023' using message='Некорректный маркер'; end if;
    select * into p from fauxlore.provinces where id=(body->>'province_id')::integer;
    if not found then raise sqlstate 'P0002' using message='Провинция не найдена'; end if;
    if jsonb_typeof(body->'x') is distinct from 'number' or jsonb_typeof(body->'y') is distinct from 'number' or
      (body->>'x')::numeric<(p.bbox->>0)::numeric or (body->>'x')::numeric>=(p.bbox->>2)::numeric or
      (body->>'y')::numeric<(p.bbox->>1)::numeric or (body->>'y')::numeric>=(p.bbox->>3)::numeric then
      raise sqlstate '22023' using message='Точка не совпадает с выбранной провинцией'; end if;
    state_value:=(body->>'state_id')::integer;
    if state_value is null then select category_id into state_value from fauxlore.province_values where province_id=p.id and layer='states'; end if;
    insert into fauxlore.map_markers(province_id,x,y,type,name,state_id)
      values(p.id,(body->>'x')::float8,(body->>'y')::float8,body->>'type',fauxlore.normalize('name',body->'name')#>>'{}',state_value) returning * into m;
    result:=to_jsonb(m)||jsonb_build_object('state_name',(select name from fauxlore.map_categories where layer='states' and id=m.state_id));
  elsif path~'^admin/markers/\d+$' and method='DELETE' then
    marker_id:=split_part(path,'/',3)::bigint; delete from fauxlore.map_markers where id=marker_id;
    if not found then raise sqlstate 'P0002' using message='Маркер не найден'; end if;
    result:=jsonb_build_object('id',marker_id,'deleted',true);
  else raise sqlstate 'P0002' using message='Метод API не найден';
  end if;
  if path like 'admin/provinces/%' and path<>'admin/provinces/bulk-preview' or path like 'admin/markers%' or path like 'admin/categories/%' or path like 'admin/roads%' or path like 'provinces/%' then
    update fauxlore._settings set value_json=to_jsonb((value_json#>>'{}')::bigint+1) where key='data_revision';
  end if;
  insert into fauxlore.operations(account_id,request_id,fingerprint,result) values(a.id,api.request_id,fingerprint,result);
  return result;
end $$;


