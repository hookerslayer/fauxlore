-- Player state applications, province reservations, review notifications and
-- the transactional conversion of an accepted application into a player state.
create table if not exists fauxlore.state_applications (
  id bigint generated by default as identity primary key,
  account_id bigint not null references fauxlore.accounts on delete cascade,
  status text not null default 'На рассмотрении'
    check(status in ('На рассмотрении','Принято','Отклонено')),
  state_name text not null,
  state_color text not null check(state_color ~ '^#[0-9a-fA-F]{6}$'),
  principles jsonb not null check(jsonb_typeof(principles)='object'),
  ruler_name text not null,
  ruler_gender text not null check(ruler_gender in ('Мужской','Женский','Иной')),
  ruler_title text not null,
  ruler_age smallint not null check(ruler_age>=30),
  race_id integer not null,
  religion_id integer not null,
  history text not null check(length(history) between 1500 and 4000),
  province_ids integer[] not null check(cardinality(province_ids)=5),
  capital_province_id integer not null,
  capital_name text not null,
  emblem_base64 text not null,
  emblem_type text not null check(emblem_type in ('image/jpeg','image/png','image/webp')),
  rejection_reason text,
  state_id integer,
  reviewed_by bigint references fauxlore.accounts(id),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  unique(id,account_id),
  check(capital_province_id=any(province_ids))
);
create unique index if not exists state_applications_one_pending_per_account
  on fauxlore.state_applications(account_id) where status='На рассмотрении';
create table if not exists fauxlore.application_provinces (
  province_id integer primary key references fauxlore.provinces on delete cascade,
  application_id bigint not null references fauxlore.state_applications on delete cascade
);
create index if not exists application_provinces_application_idx on fauxlore.application_provinces(application_id);
create table if not exists fauxlore.notifications (
  id bigint generated by default as identity primary key,
  account_id bigint not null references fauxlore.accounts on delete cascade,
  kind text not null,
  title text not null,
  message text not null,
  application_id bigint references fauxlore.state_applications on delete set null,
  created_at timestamptz not null default now(),
  read_at timestamptz
);
create index if not exists notifications_unread_idx on fauxlore.notifications(account_id,created_at desc) where read_at is null;
alter table fauxlore.state_applications enable row level security;
alter table fauxlore.application_provinces enable row level security;
alter table fauxlore.notifications enable row level security;
revoke all on fauxlore.state_applications,fauxlore.application_provinces,fauxlore.notifications from public,anon,authenticated;

alter table fauxlore.state_profiles
  add column if not exists ruler_name text,
  add column if not exists ruler_gender text,
  add column if not exists ruler_title text,
  add column if not exists ruler_age smallint,
  add column if not exists state_history text,
  add column if not exists capital_province_id integer references fauxlore.provinces(id),
  add column if not exists capital_name text,
  add column if not exists treasury numeric(14,2) not null default 0,
  add column if not exists prestige numeric(12,2) not null default 0,
  add column if not exists recruits integer not null default 0;

create or replace function fauxlore.registration_api(path text,method text,body jsonb,request_id uuid)
returns jsonb language plpgsql security definer set search_path='' as $$
declare a fauxlore.accounts; result jsonb; app fauxlore.state_applications; app_id bigint;
  state_value integer; state_name text; race_value integer; religion_value integer;
  province_value integer; province_item fauxlore.provinces; image_data text; image_bytes bytea;
  form_value text; status_value text; reason_value text; notification_value bigint;
  distinct_count integer; previous fauxlore.operations; fingerprint text;
begin
  a:=fauxlore.current_account();
  if method='GET' and path='my/applications' then
    select coalesce(jsonb_agg(to_jsonb(x) order by x.created_at desc),'[]'::jsonb) into result
      from (select id,status,state_name,state_color,principles,ruler_name,ruler_gender,ruler_title,ruler_age,
        race_id,religion_id,history,province_ids,capital_province_id,capital_name,emblem_type,
        rejection_reason,state_id,created_at,reviewed_at from fauxlore.state_applications where account_id=a.id) x;
    return result;
  elsif method='GET' and path='notifications' then
    return coalesce((select jsonb_agg(jsonb_build_object('id',n.id,'kind',n.kind,'title',n.title,'message',n.message,
      'application_id',n.application_id,'created_at',n.created_at,'read',n.read_at is not null)
      order by n.created_at desc) from fauxlore.notifications n where n.account_id=a.id),'[]'::jsonb);
  elsif method='GET' and path='admin/applications' then
    if a.role<>'admin' then raise sqlstate '42501' using message='Нужна роль администратора'; end if;
    return coalesce((select jsonb_agg(to_jsonb(x) order by x.created_at) from (
      select sa.*,ac.nickname as applicant_nickname,ac.email as applicant_email
      from fauxlore.state_applications sa join fauxlore.accounts ac on ac.id=sa.account_id
      where sa.status='На рассмотрении') x),'[]'::jsonb);
  end if;
  if request_id is null then raise sqlstate '22023' using message='Нужен идентификатор команды'; end if;
  fingerprint:=md5(jsonb_build_array(method,path,body)::text);
  perform pg_advisory_xact_lock(hashtextextended(a.id::text||':'||request_id::text,0));
  select * into previous from fauxlore.operations o where o.account_id=a.id and o.request_id=registration_api.request_id;
  if found then
    if previous.fingerprint<>fingerprint then raise sqlstate '22023' using message='Идентификатор команды уже использован'; end if;
    return previous.result;
  end if;
  if method='POST' and path='my/applications' then
    if body-array['state_name','state_color','principles','ruler_name','ruler_gender','ruler_title','ruler_age',
      'race_id','religion_id','history','province_ids','capital_province_id','capital_name','emblem_data','rules_acknowledged']<>'{}' then
      raise sqlstate '22023' using message='Анкета содержит неизвестные поля'; end if;
    if body->>'rules_acknowledged'<>'true' then raise sqlstate '22023' using message='Подтвердите, что изучили Правила и Механики'; end if;
    state_name:=nullif(btrim(body->>'state_name'),'');
    if state_name is null or length(state_name)>100 then raise sqlstate '22023' using message='Укажите название государства до 100 символов'; end if;
    if body->>'state_color' !~ '^#[0-9a-fA-F]{6}$' then raise sqlstate '22023' using message='Выберите цвет государства'; end if;
    if length(btrim(coalesce(body->>'ruler_name','')))<2 or length(btrim(coalesce(body->>'ruler_title','')))<2 then
      raise sqlstate '22023' using message='Заполните имя и титул правителя'; end if;
    if body->>'ruler_gender' not in ('Мужской','Женский','Иной') or coalesce((body->>'ruler_age')::integer,0)<30 then
      raise sqlstate '22023' using message='Возраст правителя должен быть не менее 30 лет'; end if;
    if length(coalesce(body->>'history','')) not between 1500 and 4000 then raise sqlstate '22023' using message='История должна содержать от 1500 до 4000 символов'; end if;
    if jsonb_typeof(body->'principles') is distinct from 'object' or
      (body->'principles')-array['authority','structure','economy','military','ephemeral']<>'{}'::jsonb or
      jsonb_object_length(body->'principles')<>5 then raise sqlstate '22023' using message='Заполните все пять принципов государства'; end if;
    form_value:=fauxlore.government_form(body->'principles');
    race_value:=(body->>'race_id')::integer; religion_value:=(body->>'religion_id')::integer;
    if not exists(select 1 from fauxlore.map_categories where layer='races' and id=race_value) or
       not exists(select 1 from fauxlore.map_categories where layer='religions' and id=religion_value) then
      raise sqlstate '22023' using message='Официальная раса или религия не найдена'; end if;
    if jsonb_typeof(body->'province_ids') is distinct from 'array' or jsonb_array_length(body->'province_ids')<>5 then
      raise sqlstate '22023' using message='Выберите ровно пять провинций'; end if;
    select count(distinct v::integer) into distinct_count from jsonb_array_elements_text(body->'province_ids') e(v);
    if distinct_count<>5 then raise sqlstate '22023' using message='Провинции не должны повторяться'; end if;
    province_value:=(body->>'capital_province_id')::integer;
    if not province_value=any(array(select v::integer from jsonb_array_elements_text(body->'province_ids') e(v))) then
      raise sqlstate '22023' using message='Столица должна находиться в одной из пяти выбранных провинций'; end if;
    perform 1 from fauxlore.provinces where id=any(array(select v::integer from jsonb_array_elements_text(body->'province_ids') e(v))) order by id for update;
    if (select count(*) from fauxlore.provinces p where p.id=any(array(select v::integer from jsonb_array_elements_text(body->'province_ids') e(v))) and p.kind='land')<>5 then
      raise sqlstate '22023' using message='Выбирать можно только сухопутные провинции'; end if;
    if exists(select 1 from fauxlore.province_values v where v.province_id=any(array(select x::integer from jsonb_array_elements_text(body->'province_ids') e(x))) and v.layer='states') or
       exists(select 1 from fauxlore.application_provinces ap where ap.province_id=any(array(select x::integer from jsonb_array_elements_text(body->'province_ids') e(x)))) then
      raise sqlstate '23505' using message='Одна или несколько провинций уже принадлежат государству или зарезервированы другой заявкой'; end if;
    image_data:=body->>'emblem_data';
    if image_data !~ '^data:image/(png|jpeg|webp);base64,[A-Za-z0-9+/=\r\n]+$' then raise sqlstate '22023' using message='Загрузите символику в формате JPG, PNG или WebP'; end if;
    begin image_bytes:=decode(split_part(image_data,',',2),'base64'); exception when others then raise sqlstate '22023' using message='Не удалось прочитать файл символики'; end;
    if octet_length(image_bytes)>2097152 then raise sqlstate '22023' using message='Символика должна быть не больше 2 МБ'; end if;
    if exists(select 1 from fauxlore.state_applications where account_id=a.id and status='На рассмотрении') then
      raise sqlstate '23505' using message='У вас уже есть заявка на рассмотрении'; end if;
    insert into fauxlore.state_applications(account_id,state_name,state_color,principles,ruler_name,ruler_gender,ruler_title,ruler_age,
      race_id,religion_id,history,province_ids,capital_province_id,capital_name,emblem_base64,emblem_type)
      values(a.id,state_name,lower(body->>'state_color'),body->'principles',btrim(body->>'ruler_name'),body->>'ruler_gender',
        btrim(body->>'ruler_title'),(body->>'ruler_age')::smallint,race_value,religion_value,body->>'history',
        array(select v::integer from jsonb_array_elements_text(body->'province_ids') e(v)),province_value,
        btrim(body->>'capital_name'),split_part(image_data,',',2),split_part(substr(image_data,6),';',1)) returning * into app;
    insert into fauxlore.application_provinces(province_id,application_id) select unnest(app.province_ids),app.id;
    insert into fauxlore.notifications(account_id,kind,title,message,application_id)
      select id,'application_submitted','Новая анкета государства',a.nickname||' отправил анкету «'||app.state_name||'».',app.id
      from fauxlore.accounts where role='admin';
    result:=jsonb_build_object('id',app.id,'status',app.status,'state_name',app.state_name,'created_at',app.created_at,
      'province_ids',to_jsonb(app.province_ids),'capital_province_id',app.capital_province_id,'form_name',form_value);
  elsif method='PATCH' and path~'^notifications/[0-9]+/read$' then
    update fauxlore.notifications set read_at=coalesce(read_at,now()) where id=split_part(path,'/',2)::bigint and account_id=a.id;
    if not found then raise sqlstate 'P0002' using message='Уведомление не найдено'; end if;
    result:=jsonb_build_object('ok',true);
  elsif method='PATCH' and path~'^admin/applications/[0-9]+$' then
    if a.role<>'admin' then raise sqlstate '42501' using message='Нужна роль администратора'; end if;
    app_id:=split_part(path,'/',3)::bigint;status_value:=body->>'status';reason_value:=nullif(btrim(body->>'rejection_reason'),'');
    if body-array['status','rejection_reason']<>'{}' or status_value not in ('Принято','Отклонено') then raise sqlstate '22023' using message='Выберите решение по анкете'; end if;
    select * into app from fauxlore.state_applications where id=app_id and status='На рассмотрении' for update;
    if not found then raise sqlstate 'P0002' using message='Анкета не найдена или уже рассмотрена'; end if;
    if status_value='Отклонено' then
      if length(coalesce(reason_value,''))<5 or length(reason_value)>1000 then raise sqlstate '22023' using message='Укажите причину отклонения (от 5 до 1000 символов)'; end if;
      update fauxlore.state_applications set status=status_value,rejection_reason=reason_value,reviewed_by=a.id,reviewed_at=now() where id=app.id;
      delete from fauxlore.application_provinces where application_id=app.id;
      insert into fauxlore.notifications(account_id,kind,title,message,application_id)
        values(app.account_id,'application_rejected','Анкета отклонена','Анкета «'||app.state_name||'» отклонена. Причина: '||reason_value,app.id);
      result:=jsonb_build_object('id',app.id,'status',status_value,'rejection_reason',reason_value);
    else
      perform 1 from fauxlore.provinces where id=any(app.province_ids) order by id for update;
      if exists(select 1 from fauxlore.province_values v where v.province_id=any(app.province_ids) and v.layer='states') then
        raise sqlstate '23505' using message='Выбранная провинция уже занята. Анкету нельзя принять.'; end if;
      perform pg_advisory_xact_lock(hashtextextended('fauxlore:state-category',0));
      select coalesce(max(id),0)+1 into state_value from fauxlore.map_categories where layer='states';
      state_name:=app.state_name; form_value:=fauxlore.government_form(app.principles);
      insert into fauxlore.map_categories(layer,id,name,color) values('states',state_value,app.state_name,app.state_color);
      insert into fauxlore.state_profiles(state_id,is_npc,principles,government_name,official_race_id,official_religion_id,
        created_by,emblem_base64,emblem_type,ruler_name,ruler_gender,ruler_title,ruler_age,state_history,capital_province_id,capital_name,treasury,prestige,recruits)
        values(state_value,false,app.principles,form_value,app.race_id,app.religion_id,a.id,app.emblem_base64,app.emblem_type,
          app.ruler_name,app.ruler_gender,app.ruler_title,app.ruler_age,app.history,app.capital_province_id,app.capital_name,15000,10,0);
      insert into fauxlore.account_states(account_id,layer,state_id) values(app.account_id,'states',state_value);
      insert into fauxlore.province_values(province_id,layer,category_id) select unnest(app.province_ids),'states',state_value;
      insert into fauxlore.province_values(province_id,layer,category_id) values(app.capital_province_id,'races',app.race_id)
        on conflict(province_id,layer) do update set category_id=excluded.category_id;
      insert into fauxlore.province_values(province_id,layer,category_id) values(app.capital_province_id,'religions',app.religion_id)
        on conflict(province_id,layer) do update set category_id=excluded.category_id;
      update fauxlore.provinces set province_type=case when id=app.capital_province_id then 'Столица' else 'Регион' end,
        has_capital_marker=(id=app.capital_province_id) where id=any(app.province_ids);
      select * into province_item from fauxlore.provinces where id=app.capital_province_id;
      insert into fauxlore.map_markers(province_id,x,y,type,name,state_id)
        values(app.capital_province_id,(province_item.center->>0)::float8,(province_item.center->>1)::float8,'capital',app.capital_name,state_value);
      update fauxlore.state_applications set status=status_value,state_id=state_value,reviewed_by=a.id,reviewed_at=now() where id=app.id;
      delete from fauxlore.application_provinces where application_id=app.id;
      insert into fauxlore.notifications(account_id,kind,title,message,application_id)
        values(app.account_id,'application_accepted','Анкета принята','Создано государство «'||app.state_name||'». Казна: 15 000 G, престиж: 10 ОП. Резерв войск: 0 (лимит рекрутов ещё не рассчитан).',app.id);
      result:=jsonb_build_object('id',app.id,'status',status_value,'state_id',state_value,'state_name',state_name,'form_name',form_value,
        'treasury',15000,'prestige',10,'recruits',0,'recruit_limit',null);
      update fauxlore._settings set value_json=to_jsonb((value_json#>>'{}')::bigint+1) where key='data_revision';
    end if;
  else raise sqlstate 'P0002' using message='Метод API анкет не найден';
  end if;
  insert into fauxlore.operations(account_id,request_id,fingerprint,result) values(a.id,registration_api.request_id,fingerprint,result);
  return result;
end $$;
revoke all on function fauxlore.registration_api(text,text,jsonb,uuid) from public,anon,authenticated;
grant execute on function fauxlore.registration_api(text,text,jsonb,uuid) to anon,authenticated;

create or replace function fauxlore.map_payload() returns jsonb
language sql stable security invoker set search_path='' as $$
with s as (select jsonb_object_agg(key,value_json) as data from fauxlore._settings),
visible as (select p.* from fauxlore.provinces p cross join s where
  (p.bbox->>0)::numeric<(s.data->'region'->>2)::numeric and (p.bbox->>2)::numeric>(s.data->'region'->>0)::numeric and
  (p.bbox->>1)::numeric<(s.data->'region'->>3)::numeric and (p.bbox->>3)::numeric>(s.data->'region'->>1)::numeric),
layers as (select v.province_id,jsonb_object_agg(v.layer,jsonb_build_object('id',c.id,'name',c.name,'color',c.color)||
  case when v.layer='states' then jsonb_build_object('crime',coalesce((select sp.crime from fauxlore.state_profiles sp where sp.state_id=c.id),0.2)) else '{}'::jsonb end) data
  from fauxlore.province_values v join visible p on p.id=v.province_id join fauxlore.map_categories c on c.layer=v.layer and c.id=v.category_id group by v.province_id)
select s.data||jsonb_build_object('provinces',coalesce((select jsonb_agg(case when p.kind='sea' then to_jsonb(p)-array['province_type','population','development','taxes','production','warehouse','control','occupation','tension','has_capital_marker','has_city_marker']
  else to_jsonb(p)||jsonb_build_object('layers',coalesce(l.data,'{}'),'occupation_color',c.color) end||jsonb_build_object('application_pending',exists(select 1 from fauxlore.application_provinces ap where ap.province_id=p.id)) order by p.id)
  from visible p left join layers l on l.province_id=p.id left join fauxlore.map_categories c on c.layer='states' and lower(c.name)=lower(p.occupation)),'[]'),
  'pending_application_provinces',coalesce((select jsonb_agg(ap.province_id order by ap.province_id) from fauxlore.application_provinces ap),'[]'::jsonb),
  'roads',coalesce((select jsonb_agg(jsonb_build_object('id',r.id,'type',r.type,'anchors',r.anchors,'segments',r.segments) order by r.id) from fauxlore.map_roads r where exists(select 1 from jsonb_array_elements(r.anchors) anchor join visible p on p.id=(anchor->>'province_id')::integer)),'[]'),
  'categories',coalesce((select jsonb_agg(to_jsonb(c)||case when c.layer='states' then jsonb_build_object('crime',coalesce(sp.crime,0.2)) else '{}'::jsonb end order by c.layer,c.id) from fauxlore.map_categories c left join fauxlore.state_profiles sp on sp.state_id=c.id and c.layer='states'),'[]'),
  'markers',coalesce((select jsonb_agg(to_jsonb(m)||jsonb_build_object('state_name',c.name) order by m.id) from fauxlore.map_markers m join visible p on p.id=m.province_id left join fauxlore.map_categories c on c.layer=m.state_layer and c.id=m.state_id),'[]')) from s
$$;

create or replace function public.fauxlore_api(path text,method text default 'GET',body jsonb default '{}',request_id uuid default null)
returns jsonb language sql security invoker set search_path='' as $$
  select case when path like 'my/applications' or path like 'admin/applications%' or path='notifications' or path like 'notifications/%'
      then fauxlore.registration_api(path,method,body,request_id)
    when path ~ '^state-emblem/[0-9]+$' or path ~ '^admin/state-emblem/[0-9]+$' then fauxlore.state_emblem_api(path,method,body,request_id)
    when path='game/calendar' or path='admin/turn/advance' then fauxlore.turn_api(path,method,body,request_id)
    when path='admin/states' then fauxlore.state_api(path,method,body,request_id)
    when path='my/states' or path like 'admin/states/%' then fauxlore.game_state_api(path,method,body,request_id)
    else fauxlore.api(path,method,body,request_id) end
$$;
revoke all on function public.fauxlore_api(text,text,jsonb,uuid) from public;
grant execute on function public.fauxlore_api(text,text,jsonb,uuid) to anon,authenticated;
notify pgrst,'reload schema';
