create table if not exists fauxlore.diplomatic_proposals (
  id bigint generated by default as identity primary key,
  proposer_state_id integer not null references fauxlore.state_profiles(state_id),
  title text not null check (length(btrim(title)) between 2 and 160),
  terms text not null check (length(btrim(terms)) between 2 and 10000),
  status text not null default 'pending' check (status in ('pending','active','rejected','cancelled','ended')),
  created_by bigint not null references fauxlore.accounts(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists fauxlore.diplomatic_proposal_participants (
  proposal_id bigint not null references fauxlore.diplomatic_proposals(id) on delete cascade,
  state_id integer not null references fauxlore.state_profiles(state_id),
  decision text not null default 'pending' check (decision in ('pending','accepted','rejected')),
  decided_by bigint references fauxlore.accounts(id),
  decided_at timestamptz,
  primary key (proposal_id,state_id)
);
create index if not exists diplomatic_proposal_participant_state_idx
  on fauxlore.diplomatic_proposal_participants(state_id,proposal_id);
alter table fauxlore.diplomatic_proposals enable row level security;
alter table fauxlore.diplomatic_proposal_participants enable row level security;
revoke all on fauxlore.diplomatic_proposals,fauxlore.diplomatic_proposal_participants from public,anon,authenticated;

create or replace function fauxlore.diplomatic_proposals_api(path text,method text,body jsonb,request_id uuid default null)
returns jsonb language plpgsql security definer set search_path='' as $function$
declare actor fauxlore.accounts; proposal fauxlore.diplomatic_proposals; own_state integer; participants integer[]; chosen integer;
begin
 actor:=fauxlore.current_account();
 if actor.id is null then raise sqlstate '42501' using message='Требуется авторизация'; end if;
 if method='GET' and path='my/diplomatic-proposals' then
   return jsonb_build_object('proposals',coalesce((select jsonb_agg(
     to_jsonb(p)||jsonb_build_object('proposer_state',pc.name,'participants',coalesce((
       select jsonb_agg(jsonb_build_object('state_id',pp.state_id,'state_name',sc.name,'decision',pp.decision) order by sc.name)
       from fauxlore.diplomatic_proposal_participants pp join fauxlore.map_categories sc on sc.layer='states' and sc.id=pp.state_id
       where pp.proposal_id=p.id),'[]'::jsonb)) order by p.created_at desc)
     from fauxlore.diplomatic_proposals p join fauxlore.map_categories pc on pc.layer='states' and pc.id=p.proposer_state_id
     where actor.role='admin' or exists(select 1 from fauxlore.diplomatic_proposal_participants pp join fauxlore.account_states ast on ast.state_id=pp.state_id and ast.layer='states' where pp.proposal_id=p.id and ast.account_id=actor.id)),'[]'::jsonb));
 elsif method='POST' and path='my/diplomatic-proposals' then
   own_state:=coalesce(nullif(body->>'proposer_state_id','')::integer,(select state_id from fauxlore.account_states where account_id=actor.id order by state_id limit 1));
   if actor.role<>'admin' and not exists(select 1 from fauxlore.account_states where account_id=actor.id and state_id=own_state) then raise sqlstate '42501' using message='Нет доступа к государству-инициатору'; end if;
   if own_state is null then raise sqlstate '22023' using message='Выберите государство-инициатор'; end if;
   select array_agg(distinct value::integer) into participants from jsonb_array_elements_text(coalesce(body->'participant_state_ids','[]'::jsonb)) as x(value);
   participants:=array_remove(coalesce(participants,'{}'::integer[]),own_state);
   if cardinality(participants)<2 or cardinality(participants)>9 then raise sqlstate '22023' using message='Укажите от двух до девяти государств-участников помимо инициатора'; end if;
   if exists(select 1 from unnest(participants) i where not exists(select 1 from fauxlore.state_profiles where state_id=i)) then raise sqlstate '22023' using message='В списке есть неизвестное государство'; end if;
   insert into fauxlore.diplomatic_proposals(proposer_state_id,title,terms,created_by)
     values(own_state,left(btrim(body->>'title'),160),left(btrim(body->>'terms'),10000),actor.id) returning * into proposal;
   insert into fauxlore.diplomatic_proposal_participants(proposal_id,state_id,decision,decided_by,decided_at)
     values(proposal.id,own_state,'accepted',actor.id,now());
   foreach chosen in array participants loop insert into fauxlore.diplomatic_proposal_participants(proposal_id,state_id) values(proposal.id,chosen); end loop;
   insert into fauxlore.notifications(account_id,kind,title,message)
     select distinct ast.account_id,'diplomacy','Многостороннее предложение',proposal.title||' — требуется ответ государства.'
     from fauxlore.account_states ast where ast.layer='states' and ast.state_id=any(participants);
   return jsonb_build_object('id',proposal.id,'status',proposal.status);
 elsif path ~ '^my/diplomatic-proposals/[0-9]+/(accept|reject|cancel|end)$' and method='POST' then
   select * into proposal from fauxlore.diplomatic_proposals where id=split_part(path,'/',3)::bigint for update;
   if not found then raise sqlstate '22023' using message='Предложение не найдено'; end if;
   chosen:=nullif(body->>'state_id','')::integer;
   if chosen is null then chosen:=(select state_id from fauxlore.account_states where account_id=actor.id and state_id in (select state_id from fauxlore.diplomatic_proposal_participants where proposal_id=proposal.id) order by state_id limit 1); end if;
   if actor.role<>'admin' and not exists(select 1 from fauxlore.account_states where account_id=actor.id and state_id=chosen) then raise sqlstate '42501' using message='Нет доступа к выбранному государству'; end if;
   if split_part(path,'/',4) in ('accept','reject') then
     if proposal.status<>'pending' or not exists(select 1 from fauxlore.diplomatic_proposal_participants where proposal_id=proposal.id and state_id=chosen and decision='pending') then raise sqlstate '22023' using message='Ответ для этого государства уже дан или предложение закрыто'; end if;
     update fauxlore.diplomatic_proposal_participants set decision=case split_part(path,'/',4) when 'accept' then 'accepted' else 'rejected' end,decided_by=actor.id,decided_at=now() where proposal_id=proposal.id and state_id=chosen;
     if split_part(path,'/',4)='reject' then update fauxlore.diplomatic_proposals set status='rejected',updated_at=now() where id=proposal.id;
     elsif not exists(select 1 from fauxlore.diplomatic_proposal_participants where proposal_id=proposal.id and decision='pending') then update fauxlore.diplomatic_proposals set status='active',updated_at=now() where id=proposal.id; end if;
   elsif split_part(path,'/',4)='cancel' then
     if actor.role<>'admin' and not exists(select 1 from fauxlore.account_states where account_id=actor.id and state_id=proposal.proposer_state_id) then raise sqlstate '42501' using message='Только инициатор может отозвать предложение'; end if;
     if proposal.status<>'pending' then raise sqlstate '22023' using message='Можно отозвать только ожидающее предложение'; end if;
     update fauxlore.diplomatic_proposals set status='cancelled',updated_at=now() where id=proposal.id;
   else
     if proposal.status<>'active' then raise sqlstate '22023' using message='Завершить можно только действующий договор'; end if;
     if actor.role<>'admin' and not exists(select 1 from fauxlore.account_states ast join fauxlore.diplomatic_proposal_participants pp on pp.state_id=ast.state_id where ast.account_id=actor.id and pp.proposal_id=proposal.id) then raise sqlstate '42501' using message='Нет доступа к договору'; end if;
     update fauxlore.diplomatic_proposals set status='ended',updated_at=now() where id=proposal.id;
   end if;
   return jsonb_build_object('id',proposal.id,'status',(select status from fauxlore.diplomatic_proposals where id=proposal.id));
 end if;
 raise sqlstate '22023' using message='Неизвестное действие с дипломатическим предложением';
end
$function$;
