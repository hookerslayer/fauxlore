-- These helpers run only inside the checked dispatcher. No caller-supplied role
-- or account id is trusted. Legacy ids and roles survive the migration.
create or replace function fauxlore.current_account() returns fauxlore.accounts
language plpgsql security invoker set search_path='' as $$
declare a fauxlore.accounts; identity jsonb; email_address text; uid uuid:=auth.uid();
begin
  if uid is null then raise sqlstate '28000' using message='Войдите через Google'; end if;
  select identity_data into identity from auth.identities where user_id=uid and provider='google' limit 1;
  select lower(email) into email_address from auth.users where id=uid and email_confirmed_at is not null;
  if identity is null or email_address is null or identity->>'email_verified' is distinct from 'true'
      or coalesce(identity->>'sub','')='' then
    raise sqlstate '42501' using message='Нужен подтверждённый Google-аккаунт';
  end if;
  select * into a from fauxlore.accounts where auth_user_id=uid;
  if found then return a; end if;
  -- Serialize only linking/creating this identity, never all map writes.
  perform pg_advisory_xact_lock(hashtextextended(email_address,0));
  select * into a from fauxlore.accounts where auth_user_id=uid;
  if found then return a; end if;
  select * into a from fauxlore.accounts where google_sub=identity->>'sub' for update;
  if not found then
    select * into a from fauxlore.accounts where lower(email)=email_address and not is_test_profile for update;
    if found and (a.google_sub is not null or
        (email_address not like '%@gmail.com' and coalesce(identity->>'hd','')='')) then
      raise sqlstate '42501' using message='Для привязки старого аккаунта обратитесь к администратору';
    end if;
  end if;
  if a.id is null then
    insert into fauxlore.accounts(auth_user_id,email,nickname,google_sub)
      values(uid,email_address,left(coalesce(nullif(identity->>'name',''),split_part(email_address,'@',1)),40),identity->>'sub') returning * into a;
  else
    if a.auth_user_id is not null and a.auth_user_id<>uid then raise sqlstate '42501' using message='Аккаунт уже привязан'; end if;
    update fauxlore.accounts set auth_user_id=uid,google_sub=identity->>'sub' where id=a.id returning * into a;
  end if;
  return a;
end $$;

create or replace function fauxlore.profile(a fauxlore.accounts) returns jsonb
language sql stable security invoker set search_path='' as $$
select jsonb_build_object('id',a.id,'email',a.email,'nickname',a.nickname,'role',a.role,
  'reputation',a.reputation,'avatar_type',a.avatar_type,
  'avatar_url',case when a.avatar_base64 is null then null else 'data:'||a.avatar_type||';base64,'||a.avatar_base64 end,
  'state_ids',coalesce((select jsonb_agg(state_id order by state_id) from fauxlore.account_states where account_id=a.id),'[]'))
$$;

create or replace function fauxlore.province_payload(p fauxlore.provinces) returns jsonb
language sql stable security invoker set search_path='' as $$
select to_jsonb(p)||jsonb_build_object('layers',coalesce((select jsonb_object_agg(v.layer,
  jsonb_build_object('id',c.id,'name',c.name,'color',c.color))
  from fauxlore.province_values v join fauxlore.map_categories c on c.layer=v.layer and c.id=v.category_id
  where v.province_id=p.id),'{}'),
  'control_color',(select color from fauxlore.map_categories where layer='states' and name=p.control limit 1))
$$;

create or replace function fauxlore.map_payload() returns jsonb
language sql stable security invoker set search_path='' as $$
with s as (select jsonb_object_agg(key,value_json) as data from fauxlore._settings),
visible as (select p.* from fauxlore.provinces p cross join s where
  (p.bbox->>0)::numeric<(s.data->'region'->>2)::numeric and
  (p.bbox->>2)::numeric>(s.data->'region'->>0)::numeric and
  (p.bbox->>1)::numeric<(s.data->'region'->>3)::numeric and
  (p.bbox->>3)::numeric>(s.data->'region'->>1)::numeric),
layers as (select v.province_id,jsonb_object_agg(v.layer,jsonb_build_object('id',c.id,'name',c.name,'color',c.color)) as data
  from fauxlore.province_values v join visible p on p.id=v.province_id
  join fauxlore.map_categories c on c.layer=v.layer and c.id=v.category_id group by v.province_id)
select s.data||jsonb_build_object('provinces',coalesce((select jsonb_agg(case when p.kind='sea' then
  to_jsonb(p)-array['province_type','courts','population','development','taxes','production','warehouse','control','tension','has_capital_marker','has_city_marker']
  else to_jsonb(p)||jsonb_build_object('layers',coalesce(l.data,'{}'),'control_color',c.color) end order by p.id)
  from visible p left join layers l on l.province_id=p.id left join fauxlore.map_categories c on c.layer='states' and c.name=p.control),'[]'),
  'categories',coalesce((select jsonb_agg(to_jsonb(c) order by layer,id) from fauxlore.map_categories c),'[]'),
  'markers',coalesce((select jsonb_agg(to_jsonb(m)||jsonb_build_object('state_name',c.name) order by m.id)
    from fauxlore.map_markers m join visible p on p.id=m.province_id
    left join fauxlore.map_categories c on c.layer=m.state_layer and c.id=m.state_id),'[]')) from s
$$;

create or replace function fauxlore.layer_for(field text) returns text
language sql immutable security invoker set search_path='' as $$
select case field when 'race' then 'races' when 'religion' then 'religions' when 'state' then 'states'
  when 'resource' then 'resources' when 'trade' then 'trade' when 'climate' then 'climate' end
$$;

create or replace function fauxlore.normalize(field text, value jsonb) returns jsonb
language plpgsql immutable security invoker set search_path='' as $$
declare t text:=nullif(btrim(value#>>'{}'),''); limit_length integer;
begin
  if field is null then raise sqlstate '22023' using message='Неизвестный параметр'; end if;
  if field in ('capital','city') then
    if jsonb_typeof(value) is distinct from 'boolean' then raise sqlstate '22023' using message='Укажите да или нет'; end if;
    return value;
  elsif field in ('courts','development') then
    if value='null' and field='development' then return value; end if;
    if jsonb_typeof(value) is distinct from 'number' or t!~'^\d+$' or
      t::numeric>(case when field='courts' then 100000000 else 1000000 end) then
      raise sqlstate '22023' using message='Укажите целое неотрицательное число'; end if;
    return value;
  elsif field='province_type' then
    if t is null or t not in ('Столица','Город','Регион','Колония','Нейтральная') then raise sqlstate '22023' using message='Неизвестный тип провинции'; end if;
  elsif field='terrain_type' then
    if value='null' then return value; end if;
    if t is null or t not in ('forest','marsh') then raise sqlstate '22023' using message='Неизвестный тип местности'; end if;
  elsif field='name' then
    if t is null then raise sqlstate '22023' using message='Укажите название'; end if;
  elsif field<>'control' and fauxlore.layer_for(field) is null then
    raise sqlstate '22023' using message='Неизвестный параметр';
  end if;
  if value<>'null' and jsonb_typeof(value)<>'string' then raise sqlstate '22023' using message='Некорректное текстовое значение'; end if;
  limit_length:=case when field='name' then 120 when field in ('control','state') then 100 else 80 end;
  if length(t)>limit_length then raise sqlstate '22023' using message='Слишком длинное значение'; end if;
  return coalesce(to_jsonb(t),'null');
end $$;

create or replace function fauxlore.category(layer_name text, category_name text, may_create boolean default false) returns integer
language plpgsql security invoker set search_path='' as $$
declare result integer; color_value text;
begin
  if category_name is null then return null; end if;
  select id into result from fauxlore.map_categories where layer=layer_name and lower(name)=lower(category_name);
  if result is null and may_create then
    -- Only creation of category identifiers is serialized, not province edits.
    perform pg_advisory_xact_lock(hashtextextended('category:'||layer_name,0));
    select id into result from fauxlore.map_categories where layer=layer_name and lower(name)=lower(category_name);
    if result is null then
      select coalesce(max(id),0)+1 into result from fauxlore.map_categories where layer=layer_name;
      color_value:='#'||substr(md5(category_name),1,6);
      insert into fauxlore.map_categories values(layer_name,result,category_name,color_value);
    end if;
  end if;
  if result is null then raise sqlstate '22023' using message='Неизвестное значение: '||category_name; end if;
  return result;
end $$;

create or replace function fauxlore.edit_province(province_id integer, changes jsonb) returns jsonb
language plpgsql security invoker set search_path='' as $$
declare p fauxlore.provinces; item record; value jsonb; layer_name text; category_id integer; column_name text;
begin
  select * into p from fauxlore.provinces where id=province_id for update;
  if not found then raise sqlstate 'P0002' using message='Провинция не найдена'; end if;
  if p.kind<>'land' then raise sqlstate '22023' using message='Редактировать можно только сухопутные провинции'; end if;
  if jsonb_typeof(changes)<>'object' or changes='{}' then raise sqlstate '22023' using message='Нет изменений'; end if;
  for item in select * from jsonb_each(changes) order by key loop
    value:=fauxlore.normalize(item.key,item.value); layer_name:=fauxlore.layer_for(item.key);
    if layer_name is not null then
      category_id:=fauxlore.category(layer_name,value#>>'{}',layer_name='states');
      if category_id is null then
        delete from fauxlore.province_values v where v.province_id=p.id and v.layer=layer_name;
      else
        insert into fauxlore.province_values values(p.id,layer_name,category_id)
          on conflict on constraint province_values_pkey do update set category_id=excluded.category_id;
      end if;
    else
      if item.key='control' and value<>'null' then perform fauxlore.category('states',value#>>'{}',true); end if;
      column_name:=case item.key when 'capital' then 'has_capital_marker' when 'city' then 'has_city_marker' else item.key end;
      p:=jsonb_populate_record(p,jsonb_build_object(column_name,value));
    end if;
  end loop;
  if changes?'courts' then p.population:=p.courts::bigint*4; end if;
  if p.has_capital_marker then p.province_type:='Столица';
  elsif p.has_city_marker then p.province_type:='Город';
  elsif not changes?'province_type' and changes ?| array['capital','city','state'] then
    p.province_type:=case when exists(select 1 from fauxlore.province_values v where v.province_id=p.id and layer='states') then 'Регион' else 'Нейтральная' end;
  end if;
  update fauxlore.provinces set name=p.name,province_type=p.province_type,courts=p.courts,population=p.population,
    development=p.development,control=p.control,terrain_type=p.terrain_type,
    has_capital_marker=p.has_capital_marker,has_city_marker=p.has_city_marker where id=p.id;
  return fauxlore.province_payload(p);
end $$;

create or replace function fauxlore.bulk_edit(body jsonb, apply_changes boolean) returns jsonb
language plpgsql security invoker set search_path='' as $$
declare rule jsonb; rules jsonb:='[]'; counts jsonb:='[]'; changes jsonb; merged jsonb:='{}';
  expected jsonb; actual jsonb; p fauxlore.provinces; entry record; total integer:=0; conflicts integer:=0;
  conflict_ids jsonb:='[]'; i integer; count_i integer; bounds jsonb; payload jsonb;
begin
  if jsonb_typeof(body->'rules') is distinct from 'array' or jsonb_array_length(body->'rules') not between 1 and 50 then
    raise sqlstate '22023' using message='Нужно от 1 до 50 правил'; end if;
  for rule in select * from jsonb_array_elements(body->'rules') loop
    if rule->>'target_field'='name' then raise sqlstate '22023' using message='Массовое переименование отключено'; end if;
    rule:=rule||jsonb_build_object('condition_value',fauxlore.normalize(rule->>'condition_field',coalesce(rule->'condition_value','null')),
      'target_value',fauxlore.normalize(rule->>'target_field',coalesce(rule->'target_value','null')));
    if fauxlore.layer_for(rule->>'condition_field') is not null then
      perform fauxlore.category(fauxlore.layer_for(rule->>'condition_field'),rule->>'condition_value',false); end if;
    if fauxlore.layer_for(rule->>'target_field') is not null and rule->>'target_field'<>'state' then
      perform fauxlore.category(fauxlore.layer_for(rule->>'target_field'),rule->>'target_value',false); end if;
    rules:=rules||jsonb_build_array(rule); counts:=counts||'0'::jsonb;
  end loop;
  select value_json into bounds from fauxlore._settings where key='region';
  for p in select * from fauxlore.provinces where kind='land'
    and (center->>0)::numeric>=(bounds->>0)::numeric and (center->>0)::numeric<(bounds->>2)::numeric
    and (center->>1)::numeric>=(bounds->>1)::numeric and (center->>1)::numeric<(bounds->>3)::numeric order by id loop
    changes:='{}'; payload:=fauxlore.province_payload(p);
    for i in 0..jsonb_array_length(rules)-1 loop
      rule:=rules->i; expected:=rule->'condition_value';
      if fauxlore.layer_for(rule->>'condition_field') is not null then
        actual:=coalesce(payload->'layers'->fauxlore.layer_for(rule->>'condition_field')->'name','null');
      else
        actual:=coalesce(payload->(case rule->>'condition_field' when 'capital' then 'has_capital_marker' when 'city' then 'has_city_marker' else rule->>'condition_field' end),'null');
      end if;
      if lower(actual::text)<>lower(expected::text) then continue; end if;
      count_i:=(counts->>i)::integer+1; counts:=jsonb_set(counts,array[i::text],to_jsonb(count_i));
      if changes?(rule->>'target_field') and changes->(rule->>'target_field')<>rule->'target_value' then
        if not conflict_ids@>jsonb_build_array(p.id) then conflicts:=conflicts+1; conflict_ids:=conflict_ids||to_jsonb(p.id); end if;
      end if;
      changes:=changes||jsonb_build_object(rule->>'target_field',rule->'target_value');
    end loop;
    if changes<>'{}' then total:=total+1; merged:=merged||jsonb_build_object(p.id::text,changes); end if;
  end loop;
  if not apply_changes then return jsonb_build_object('rule_counts',counts,'total',total,'conflict_count',conflicts,'conflict_examples',conflict_ids); end if;
  if conflicts>0 then raise sqlstate '22023' using message='Правила пересекаются и задают разные значения одному параметру'; end if;
  for entry in select * from jsonb_each(merged) order by key::integer loop perform fauxlore.edit_province(entry.key::integer,entry.value); end loop;
  return jsonb_build_object('updated_count',total,'rule_counts',counts);
end $$;

-- The sole privileged dispatcher. Its read-only public routes return only the
-- public map. Every other operation checks auth.uid() and a database-owned role.
create or replace function fauxlore.api(path text, method text, body jsonb, request_id uuid) returns jsonb
language plpgsql security definer set search_path='' as $$
declare a fauxlore.accounts; p fauxlore.provinces; m fauxlore.map_markers; result jsonb;
  previous fauxlore.operations; fingerprint text; id_value integer; marker_id bigint; state_value integer;
  avatar text; mime_value text; changes jsonb;
begin
  if length(path)>150 or method not in ('GET','POST','PATCH','PUT','DELETE') or
    jsonb_typeof(body) is distinct from 'object' or octet_length(body::text)>2900000 then
    raise sqlstate '22023' using message='Некорректный запрос'; end if;
  if path='health' and method='GET' then return jsonb_build_object('ok',true,'database','supabase'); end if;
  if path='map' and method='GET' then
    if not exists(select 1 from fauxlore._settings where key='migration_ready' and value_json='true') then
      raise sqlstate '55000' using message='Перенос данных ещё не завершён'; end if;
    return fauxlore.map_payload();
  end if;
  if path='auth/me' and method='GET' and auth.uid() is null then return '{"user":null}'; end if;
  a:=fauxlore.current_account();
  if path like 'admin/%' and a.role<>'admin' then raise sqlstate '42501' using message='Нужна роль администратора'; end if;
  if path='auth/me' and method='GET' then return jsonb_build_object('user',fauxlore.profile(a)); end if;
  if path='profile' and method='GET' then return fauxlore.profile(a); end if;
  if path='preferences' and method='GET' then return coalesce((select settings from fauxlore.user_preferences where account_id=a.id),'{}'); end if;
  if method='GET' then raise sqlstate 'P0002' using message='Метод API не найден'; end if;
  if request_id is null then raise sqlstate '22023' using message='Нужен идентификатор команды'; end if;
  fingerprint:=md5(jsonb_build_array(method,path,body)::text);
  perform pg_advisory_xact_lock(hashtextextended(a.id::text||':'||request_id::text,0));
  select * into previous from fauxlore.operations o where account_id=a.id and o.request_id=api.request_id;
  if found then
    if previous.fingerprint<>fingerprint then raise sqlstate '22023' using message='Идентификатор команды уже использован'; end if;
    return previous.result;
  end if;
  if path='preferences' and method='PUT' then
    select coalesce(jsonb_object_agg(key,value),'{}') into changes from jsonb_each(body) where key=any(array['layer','markers','information','showIds']);
    if octet_length(changes::text)>8192 then raise sqlstate '22023' using message='Слишком большой набор настроек'; end if;
    insert into fauxlore.user_preferences values(a.id,changes) on conflict(account_id) do update set settings=excluded.settings;
    result:='{"ok":true}';
  elsif path='profile/avatar' and method='POST' then
    avatar:=body->>'image_data';
    if avatar is not null then
      if avatar!~'^data:image/(png|jpeg|gif|webp);base64,[A-Za-z0-9+/=\r\n]+$' then raise sqlstate '22023' using message='Неподдерживаемое изображение'; end if;
      mime_value:=split_part(substr(avatar,6),';',1);avatar:=split_part(avatar,',',2);
      if octet_length(decode(avatar,'base64'))>2097152 then raise sqlstate '22023' using message='Аватар должен быть не больше 2 МБ'; end if;
    end if;
    update fauxlore.accounts set avatar_base64=avatar,avatar_type=mime_value where id=a.id;
    result:='{"ok":true}';
  elsif path~'^admin/categories/(states|races|religions|resources|trade|climate)/[0-9]+$' and method='PATCH' then
    if body-'color'<>'{}' or jsonb_typeof(body->'color') is distinct from 'string' or
      (body->>'color')!~'^#[0-9a-fA-F]{6}$' then
      raise sqlstate '22023' using message='Укажите цвет в формате #RRGGBB'; end if;
    update fauxlore.map_categories set color=lower(body->>'color')
      where layer=split_part(path,'/',3) and id=split_part(path,'/',4)::integer
      returning to_jsonb(map_categories.*) into result;
    if not found then raise sqlstate 'P0002' using message='Значение параметра не найдено'; end if;
  elsif path in ('admin/provinces/bulk-preview','admin/provinces/bulk-edit') and method='POST' then
    result:=fauxlore.bulk_edit(body,path='admin/provinces/bulk-edit');
  elsif path~'^admin/provinces/\d+$' and method='PATCH' then
    result:=fauxlore.edit_province(split_part(path,'/',3)::integer,body);
  elsif path~'^provinces/\d+/name$' and method='PATCH' then
    id_value:=split_part(path,'/',2)::integer;
    if not exists(select 1 from fauxlore.province_values v join fauxlore.account_states s
      on s.state_id=v.category_id and s.account_id=a.id where v.province_id=id_value and v.layer='states') then
      raise sqlstate '42501' using message='Вы не владеете государством этой провинции'; end if;
    if body-'name'<>'{}' then raise sqlstate '22023' using message='Разрешено менять только название'; end if;
    result:=fauxlore.edit_province(id_value,body);result:=jsonb_build_object('id',id_value,'name',result->'name');
  elsif path='admin/markers' and method='POST' then
    if body-array['province_id','x','y','type','name','state_id']<>'{}' or body->>'type' not in ('capital','city','fortress','port') then
      raise sqlstate '22023' using message='Некорректный маркер'; end if;
    select * into p from fauxlore.provinces where id=(body->>'province_id')::integer;
    if not found then raise sqlstate 'P0002' using message='Провинция не найдена'; end if;
    if jsonb_typeof(body->'x') is distinct from 'number' or jsonb_typeof(body->'y') is distinct from 'number' or
      (body->>'x')::numeric<(p.bbox->>0)::numeric or (body->>'x')::numeric>=(p.bbox->>2)::numeric or
      (body->>'y')::numeric<(p.bbox->>1)::numeric or (body->>'y')::numeric>=(p.bbox->>3)::numeric then
      raise sqlstate '22023' using message='Точка не совпадает с выбранной провинцией'; end if;
    state_value:=(body->>'state_id')::integer;
    if state_value is null then select category_id into state_value from fauxlore.province_values where province_id=p.id and layer='states'; end if;
    insert into fauxlore.map_markers(province_id,x,y,type,name,state_id)
      values(p.id,(body->>'x')::float8,(body->>'y')::float8,body->>'type',fauxlore.normalize('name',body->'name')#>>'{}',state_value) returning * into m;
    result:=to_jsonb(m)||jsonb_build_object('state_name',(select name from fauxlore.map_categories where layer='states' and id=m.state_id));
  elsif path~'^admin/markers/\d+$' and method='DELETE' then
    marker_id:=split_part(path,'/',3)::bigint; delete from fauxlore.map_markers where id=marker_id;
    if not found then raise sqlstate 'P0002' using message='Маркер не найден'; end if;
    result:=jsonb_build_object('id',marker_id,'deleted',true);
  else raise sqlstate 'P0002' using message='Метод API не найден';
  end if;
  if path like 'admin/provinces/%' and path<>'admin/provinces/bulk-preview' or path like 'admin/markers%' or path like 'admin/categories/%' or path like 'provinces/%' then
    update fauxlore._settings set value_json=to_jsonb((value_json#>>'{}')::bigint+1) where key='data_revision';
  end if;
  insert into fauxlore.operations(account_id,request_id,fingerprint,result) values(a.id,api.request_id,fingerprint,result);
  return result;
end $$;

