-- Application tables stay outside the exposed Data API schema.
create schema if not exists fauxlore;
revoke all on schema fauxlore from public, anon, authenticated;
alter default privileges in schema fauxlore revoke execute on functions from public;

create table if not exists fauxlore.provinces (
  id integer primary key check (id > 0 and id < 16777216),
  kind text not null check (kind in ('land','sea','lake')),
  name text not null, center jsonb not null, bbox jsonb not null,
  area bigint not null check (area > 0), seed_area bigint not null,
  population bigint not null default 0 check (population >= 0),
  development integer check (development between 0 and 1000000),
  province_type text not null default 'Нейтральная'
    check (province_type in ('Столица','Город','Регион','Колония','Нейтральная')),
  courts integer not null default 0 check (courts between 0 and 100000000),
  control text, terrain_type text check (terrain_type in ('forest','marsh')),
  has_capital_marker boolean not null default false,
  has_city_marker boolean not null default false,
  taxes numeric, production jsonb, warehouse jsonb, tension numeric
);
create table if not exists fauxlore.map_categories (
  layer text not null check (layer in ('states','races','religions','resources','trade','climate')),
  id integer not null, name text not null,
  color text not null check (color ~ '^#[0-9a-fA-F]{6}$'), primary key (layer,id)
);
create unique index if not exists category_name_idx on fauxlore.map_categories(layer,lower(name));
create table if not exists fauxlore.province_values (
  province_id integer not null references fauxlore.provinces on delete cascade,
  layer text not null, category_id integer not null, primary key (province_id,layer),
  foreign key (layer,category_id) references fauxlore.map_categories
);
create index if not exists province_category_idx on fauxlore.province_values(layer,category_id,province_id);
create table if not exists fauxlore.map_markers (
  id bigint generated by default as identity primary key,
  province_id integer not null references fauxlore.provinces,
  x double precision not null, y double precision not null,
  type text not null check (type in ('capital','city','fortress','port')),
  name text not null check (length(name) between 1 and 120),
  state_layer text not null default 'states' check (state_layer='states'), state_id integer,
  description text check (description is null), created_at timestamptz not null default now(),
  foreign key (state_layer,state_id) references fauxlore.map_categories
);
create index if not exists marker_province_idx on fauxlore.map_markers(province_id);
create index if not exists marker_state_idx on fauxlore.map_markers(state_layer,state_id);
create table if not exists fauxlore.accounts (
  id bigint generated by default as identity primary key,
  auth_user_id uuid unique references auth.users(id) on delete set null,
  email text not null unique, nickname text not null,
  role text not null default 'player' check (role in ('player','admin')),
  created_at timestamptz not null default now(), reputation integer not null default 0,
  avatar_base64 text, avatar_type text, is_test_profile boolean not null default false,
  google_sub text unique
);
create unique index if not exists account_email_idx on fauxlore.accounts(lower(email));
create table if not exists fauxlore.account_states (
  account_id bigint not null references fauxlore.accounts on delete cascade,
  layer text not null default 'states' check (layer='states'), state_id integer not null,
  primary key (account_id,state_id), foreign key (layer,state_id) references fauxlore.map_categories
);
create index if not exists account_state_idx on fauxlore.account_states(layer,state_id);
create table if not exists fauxlore.user_preferences (
  account_id bigint primary key references fauxlore.accounts on delete cascade,
  settings jsonb not null default '{}'
);
create table if not exists fauxlore._settings (key text primary key, value_json jsonb not null);
create table if not exists fauxlore.archived_markers (id bigint primary key, payload jsonb not null);
create table if not exists fauxlore.operations (
  account_id bigint not null references fauxlore.accounts on delete cascade,
  request_id uuid not null, fingerprint text not null, result jsonb not null,
  created_at timestamptz not null default now(), primary key (account_id,request_id)
);
create table if not exists fauxlore.import_batches (
  id text primary key, sha256 text not null, created_at timestamptz not null default now()
);
do $$ declare item record; begin
  for item in select tablename from pg_tables where schemaname='fauxlore' loop
    execute format('alter table fauxlore.%I enable row level security',item.tablename);
  end loop;
end $$;
