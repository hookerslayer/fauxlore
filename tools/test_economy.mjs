import assert from 'node:assert/strict';
import {calculateProvinceEconomy, calculateProvinceEstateTaxes, calculateStatePolitics, DEFAULT_ECONOMY_CONFIG, setEconomyConfig} from '../economy.js';
import {estatePopulation} from '../estate-demography.js';

const province=(overrides={})=>({kind:'land',province_type:'Регион',population:1000,development:100,control:100,trade_status:'Отсутствует',layers:{states:{id:1,name:'Альфа',crime:0,corruption:0},races:{id:1,name:'Люди'},religions:{id:1,name:'Правоверие'},resources:{name:'Зерно'}},...overrides});
assert.deepEqual(estatePopulation('Регион',1000),{Знать:10,Духовенство:20,Горожане:50,Крестьяне:920});
assert.deepEqual(estatePopulation('Городская',1000),{Знать:20,Духовенство:30,Горожане:300,Крестьяне:650});
assert.deepEqual(estatePopulation('Столичная',1000),{Знать:30,Духовенство:40,Горожане:380,Крестьяне:550});
assert.equal(calculateProvinceEconomy(province(),'Альфа').grossTaxes,1190);
assert.equal(calculateProvinceEconomy(province({development:101}),'Альфа').grossTaxes,1190);
assert.equal(calculateProvinceEconomy(province({development:101}),'Альфа').production,969);
assert.equal(calculateProvinceEconomy(province({province_type:'Городская'}),'Альфа').grossTaxes,1780);
assert.equal(calculateProvinceEconomy(province({development:150}),'Альфа').grossTaxes,1190);
assert.equal(calculateProvinceEconomy(province({development:150}),'Альфа').production,1440);
assert.equal(calculateProvinceEconomy(province({control:50,development:150}),'Альфа').grossTaxes,1190);
assert.equal(calculateProvinceEconomy(province({control:50,development:150}),'Альфа').taxes,178);
const custom=province({layers:{...province().layers,states:{id:1,name:'Альфа',crime:0,corruption:0,estate_tax_rates:{Знать:20,Духовенство:1,Горожане:3,Крестьяне:1}}}});
assert.equal(calculateProvinceEconomy(custom,'Альфа').grossTaxes,1290);
assert.equal(calculateProvinceEstateTaxes(custom,'Альфа').Знать.gross,200);
assert.equal(calculateProvinceEconomy(province({development:0}),'Альфа').grossTaxes,0);
const occupied=province({occupation:'Бета',occupation_crime:0,occupation_corruption:0,occupation_estate_tax_rates:{Знать:10,Духовенство:1,Горожане:3,Крестьяне:1}});
assert.equal(calculateProvinceEconomy(occupied,'Альфа').taxes,0);
assert.equal(calculateProvinceEconomy(occupied,'Бета').grossTaxes,595);
const politics=calculateStatePolitics([province()],[{group_type:'estate',group_key:'Крестьяне',status:'Ключевое',loyalty:.5}],'Альфа');
assert.deepEqual(Object.keys(politics.estateInfluence).sort(),['Горожане','Духовенство','Знать','Крестьяне'].sort());
assert.equal(politics.estateInfluence.Корона,undefined);
setEconomyConfig(DEFAULT_ECONOMY_CONFIG);
console.log('Estate economy: population shares, rates, development, occupation and four-estate politics passed');
