import assert from 'node:assert/strict';
import {routeOnMask,lineInside} from '../road-routing.js';
const width=90,height=70,mask=new Uint8Array(width*height);mask.fill(1);
for(let y=0;y<55;y++)for(let x=35;x<45;x++)mask[y*width+x]=0;
const inside=(x,y)=>x>=0&&y>=0&&x<width&&y<height&&mask[Math.floor(y)*width+Math.floor(x)]===1;
const start=[10.5,10.5],end=[75.5,10.5];
const route=routeOnMask({width,height,mask,start,end});
assert.deepEqual(route[0],start);assert.deepEqual(route.at(-1),end);
assert.ok(route.some(p=>p[1]>=55),'must go around forbidden obstacle');
assert.ok(route.every((p,i)=>!i||lineInside(route[i-1],p,inside)),'all curve segments remain in permitted mask');
const open=new Uint8Array(width*height);open.fill(1);
const curved=routeOnMask({width,height,mask:open,start:[5.5,30.5],end:[80.5,30.5]});
assert.ok(curved.some(p=>Math.abs(p[1]-30.5)>.5),'even unobstructed roads should curve');
const wall=mask.slice();for(let y=0;y<height;y++)wall[y*width+40]=0;
assert.throws(()=>routeOnMask({width,height,mask:wall,start,end}),/Нет прохода/);
assert.throws(()=>routeOnMask({width,height,mask,start:[40,10],end}),/вне своей провинции/);
const corners=new Uint8Array([1,0,0,1]);
assert.throws(()=>routeOnMask({width:2,height:2,mask:corners,start:[.5,.5],end:[1.5,1.5]}),/Нет прохода/);
console.log('PASS: anchors, curved roads, concave obstacle containment, disconnected mask, invalid centers, no diagonal corner cuts');
